async function main() {
  console.log(`總共有 ${questionsPool.length} 道題庫範本，開始植入...`);
  let createdCount = 0;
  let skippedCount = 0;

  for (const q of questionsPool) {
    const norm = normalizeText(q.stem);
    const existing = await prisma.question.findFirst({
      where: { normalizedStem: norm },
    });
    if (!existing) {
      await prisma.question.create({
        data: {
          ...q,
          normalizedStem: norm,
        },
      });
      createdCount++;
    } else {
      skippedCount++;
    }
  }

  const total = await prisma.question.count();
  console.log(`植入完成！本次新增: ${createdCount} 題，已存在略過: ${skippedCount} 題，目前題庫總數: ${total} 題！`);
}

main()
  .catch((e) => {
    console.error("植入失敗:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
